        named_examples.to_markdown(index=False) if not named_examples.empty else "Named examples not found.",
        "",
        "## Remaining uniformity failures",
        "",
        failures.to_markdown(index=False) if not failures.empty else "No remaining uniformity failures.",
        "",
        "## Tables created",
        "",
        "- `manuscript_workspace.mig178_ptc_mtc_patient_audit_v1`",
        "- `manuscript_workspace.mig178_histology_vocab_uniformity_audit_v1`",
        "- `manuscript_workspace.mig178_histology_cleanup_summary_v1`",
