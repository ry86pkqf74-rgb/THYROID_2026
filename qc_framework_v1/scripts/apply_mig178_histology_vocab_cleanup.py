def apply_cleanup(con: duckdb.DuckDBPyConnection) -> None:
    con.execute(
        """
        UPDATE main.canonical_path_malignant_events_v1
        SET primary_histology = mig178_norm_histology(primary_histology),
            histology_variant = mig178_norm_variant(histology_variant),
            build_script = '178_histology_vocab_cleanup',
            build_ts = CAST(CURRENT_TIMESTAMP AS TIMESTAMP)
        WHERE primary_histology IS DISTINCT FROM mig178_norm_histology(primary_histology)
           OR histology_variant IS DISTINCT FROM mig178_norm_variant(histology_variant)
        """
    )
    con.execute(
        """
        CREATE OR REPLACE TEMP TABLE mig178_patient_histology_rollup AS
        SELECT
            CAST(research_id AS VARCHAR) AS research_id,
            STRING_AGG(DISTINCT primary_histology, ' | ' ORDER BY primary_histology)
              FILTER (WHERE primary_histology IS NOT NULL) AS histologic_types_all_new,
            STRING_AGG(DISTINCT histology_variant, ' | ' ORDER BY histology_variant)
              FILTER (WHERE histology_variant IS NOT NULL) AS histologic_variants_all_new
        FROM main.canonical_path_malignant_events_v1
        GROUP BY 1
        """
    )
    con.execute(
        """
        UPDATE main.canonical_patient_master AS p
        SET histologic_types_all = r.histologic_types_all_new,
            histologic_variants_all = r.histologic_variants_all_new,
            path_histology_raw = r.histologic_types_all_new,
            path_histology_variant_raw = r.histologic_variants_all_new,
            cpm_built_at = CAST(CURRENT_TIMESTAMP AS TIMESTAMP)
        FROM mig178_patient_histology_rollup r
        WHERE p.research_id = r.research_id
          AND (
            p.histologic_types_all IS DISTINCT FROM r.histologic_types_all_new OR
            p.histologic_variants_all IS DISTINCT FROM r.histologic_variants_all_new OR
            p.path_histology_raw IS DISTINCT FROM r.histologic_types_all_new OR
            p.path_histology_variant_raw IS DISTINCT FROM r.histologic_variants_all_new
          )
        """
    )
    con.execute(
        """
        UPDATE main.canonical_path_malignant_patient_rollup_v1
        SET dominant_histology = mig178_norm_histology(dominant_histology),
            poc_tumor_1_histologic_type = mig178_norm_histology(poc_tumor_1_histologic_type),
            build_script = '178_histology_vocab_cleanup',
            build_ts = CAST(CURRENT_TIMESTAMP AS TIMESTAMP)
        WHERE dominant_histology IS DISTINCT FROM mig178_norm_histology(dominant_histology)
           OR poc_tumor_1_histologic_type IS DISTINCT FROM mig178_norm_histology(poc_tumor_1_histologic_type)
        """
    )


def build_audit_tables(con: duckdb.DuckDBPyConnection) -> None:
    con.execute(
        """
        CREATE OR REPLACE TABLE manuscript_workspace.mig178_ptc_mtc_patient_audit_v1 AS
        WITH event_rollup AS (
          SELECT
            CAST(research_id AS VARCHAR) AS research_id,
            BOOL_OR(primary_histology = 'PTC') AS has_ptc,
            BOOL_OR(primary_histology = 'MTC') AS has_mtc,
            STRING_AGG(DISTINCT primary_histology, ' | ' ORDER BY primary_histology)
              FILTER (WHERE primary_histology IS NOT NULL) AS event_histologies_normalized,
            STRING_AGG(DISTINCT histology_variant, ' | ' ORDER BY histology_variant)
              FILTER (WHERE histology_variant IS NOT NULL) AS event_variants_normalized,
            COUNT(*) AS n_path_malignant_events
          FROM main.canonical_path_malignant_events_v1
          GROUP BY 1
        )
        SELECT
          e.research_id,
          e.n_path_malignant_events,
          e.event_histologies_normalized,
          e.event_variants_normalized,
          p.histologic_types_all AS pm_histologic_types_all,
          p.histologic_variants_all AS pm_histologic_variants_all,
          r.dominant_histology AS rollup_dominant_histology,
          CASE
            WHEN e.event_histologies_normalized = p.histologic_types_all THEN 'pm_matches_events'
            ELSE 'pm_event_mismatch_review'
          END AS pm_event_status,
          CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS audited_at
        FROM event_rollup e
        JOIN main.canonical_patient_master p ON p.research_id = e.research_id
        LEFT JOIN main.canonical_path_malignant_patient_rollup_v1 r
          ON CAST(r.research_id AS VARCHAR) = e.research_id
        WHERE e.has_ptc AND e.has_mtc
        ORDER BY TRY_CAST(e.research_id AS BIGINT)
        """
    )
    con.execute(
        r"""
        CREATE OR REPLACE TABLE manuscript_workspace.mig178_histology_vocab_uniformity_audit_v1 AS
        WITH values AS (
          SELECT 'canonical_patient_master' AS table_name, 'histologic_types_all' AS column_name, CAST(research_id AS VARCHAR) AS research_id, histologic_types_all AS value FROM main.canonical_patient_master
          UNION ALL SELECT 'canonical_patient_master', 'histologic_variants_all', CAST(research_id AS VARCHAR), histologic_variants_all FROM main.canonical_patient_master
          UNION ALL SELECT 'canonical_patient_master', 'path_histology_raw', CAST(research_id AS VARCHAR), path_histology_raw FROM main.canonical_patient_master
          UNION ALL SELECT 'canonical_patient_master', 'path_histology_variant_raw', CAST(research_id AS VARCHAR), path_histology_variant_raw FROM main.canonical_patient_master
          UNION ALL SELECT 'canonical_path_malignant_events_v1', 'primary_histology', CAST(research_id AS VARCHAR), primary_histology FROM main.canonical_path_malignant_events_v1
          UNION ALL SELECT 'canonical_path_malignant_events_v1', 'histology_variant', CAST(research_id AS VARCHAR), histology_variant FROM main.canonical_path_malignant_events_v1
          UNION ALL SELECT 'canonical_path_malignant_patient_rollup_v1', 'dominant_histology', CAST(research_id AS VARCHAR), dominant_histology FROM main.canonical_path_malignant_patient_rollup_v1
          UNION ALL SELECT 'canonical_path_malignant_patient_rollup_v1', 'poc_tumor_1_histologic_type', CAST(research_id AS VARCHAR), poc_tumor_1_histologic_type FROM main.canonical_path_malignant_patient_rollup_v1
        ), classified AS (
          SELECT
            table_name,
            column_name,
            value,
            COUNT(*) AS n_rows,
            COUNT(DISTINCT research_id) AS n_patients,
            CASE
              WHEN value IS NULL THEN 'null_ok'
              WHEN regexp_matches(LOWER(CAST(value AS VARCHAR)), 'mtc_ptc_mixed|mixed composit') THEN 'FAIL_mixed_composite_token'
              WHEN regexp_matches(LOWER(CAST(value AS VARCHAR)), 'metastatic|recurrent') THEN 'FAIL_metastatic_recurrent_prefix'
              WHEN regexp_matches(CAST(value AS VARCHAR), '[\r\n]') THEN 'FAIL_embedded_newline'
              WHEN regexp_matches(CAST(value AS VARCHAR), '\?') THEN 'FAIL_uncertainty_marker'
              ELSE 'PASS'
            END AS uniformity_status
          FROM values
          GROUP BY 1,2,3
        )
        SELECT *, CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS audited_at
        FROM classified
        ORDER BY
          CASE WHEN uniformity_status='PASS' THEN 2 WHEN uniformity_status='null_ok' THEN 3 ELSE 1 END,
          table_name, column_name, n_rows DESC, value
        """
    )
    con.execute(
        """
        CREATE OR REPLACE TABLE manuscript_workspace.mig178_histology_cleanup_summary_v1 AS
        SELECT * FROM (
          SELECT 'ptc_mtc_patient_audit_rows' AS metric, COUNT(*)::VARCHAR AS value FROM manuscript_workspace.mig178_ptc_mtc_patient_audit_v1
          UNION ALL
          SELECT 'uniformity_fail_values', COUNT(*)::VARCHAR FROM manuscript_workspace.mig178_histology_vocab_uniformity_audit_v1 WHERE uniformity_status LIKE 'FAIL%'
          UNION ALL
          SELECT 'uniformity_pass_values', COUNT(*)::VARCHAR FROM manuscript_workspace.mig178_histology_vocab_uniformity_audit_v1 WHERE uniformity_status = 'PASS'
          UNION ALL
          SELECT 'mtc_ptc_mixed_values_remaining', COUNT(*)::VARCHAR FROM manuscript_workspace.mig178_histology_vocab_uniformity_audit_v1 WHERE LOWER(COALESCE(value,'')) LIKE '%mtc_ptc_mixed%'
        )
        """
    )


