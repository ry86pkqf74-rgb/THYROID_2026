def install_macros(con: duckdb.DuckDBPyConnection) -> None:
    con.execute(
        r"""
        CREATE OR REPLACE TEMP MACRO mig178_clean_text(x) AS (
          NULLIF(
            regexp_replace(
              TRIM(regexp_replace(CAST(x AS VARCHAR), '[\r\n\t]+', ' ', 'g')),
              '\s+', ' ', 'g'
            ),
            ''
          )
        )
        """
    )
    con.execute(
        r"""
        CREATE OR REPLACE TEMP MACRO mig178_norm_histology(x) AS (
          CASE
            WHEN x IS NULL OR mig178_clean_text(x) IS NULL THEN NULL
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), '(papillary|paillary|\bptc\b)') THEN 'PTC'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), '(medullary|\bmtc\b)') THEN 'MTC'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'differentiated high grade') THEN 'differentiated high grade thyroid carcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'poorly differentiated') THEN 'poorly differentiated thyroid carcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'anaplastic') THEN 'anaplastic carcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'niftp') THEN 'NIFTP'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'ftump') THEN 'FTUMP'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'h[üu]rthle cell carcinoma|hurthle cell carcinoma') THEN 'Hurthle cell carcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'follicular carcinoma|insular carcinoma') THEN 'follicular carcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'angiosarcoma') THEN 'angiosarcoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'neuroendocrine') THEN 'neuroendocrine tumor'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'follicular adenoma') THEN 'follicular adenoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'thyroid carcinoma|carcinoma') THEN 'DTC (NOS)'
            ELSE mig178_clean_text(x)
          END
        )
        """
    )
    con.execute(
        r"""
        CREATE OR REPLACE TEMP MACRO mig178_norm_variant(x) AS (
          CASE
            WHEN x IS NULL OR mig178_clean_text(x) IS NULL THEN NULL
            WHEN LOWER(mig178_clean_text(x)) IN ('metastatic', 'recurrent') THEN NULL
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'microcarcioma|micorcarcinoma|microcarcinoma') THEN 'microcarcinoma'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'tall cell|tal cell|varaint') THEN 'tall cell'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'follicular') THEN 'follicular'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'classic|classical') THEN 'classical'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'hurth|oncocytic|onocytic') THEN 'oncocytic/hurthle'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'hobnail') THEN 'hobnail'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'diffuse sclerosing') THEN 'diffuse sclerosing'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'cribiform|cribriform') THEN 'cribriform morular'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'minimally invasive') THEN 'minimally invasive'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'widely invasive') THEN 'widely invasive'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'insular') THEN 'insular'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'solid') THEN 'solid'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'warthin') THEN 'warthin-like'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'macrofollicular') THEN 'macrofollicular'
            WHEN regexp_matches(LOWER(mig178_clean_text(x)), 'high grade') THEN 'high grade'
            ELSE LOWER(mig178_clean_text(x))
          END
        )
        """
    )


def create_snapshots(con: duckdb.DuckDBPyConnection, ts_tag: str) -> tuple[str, str, str]:
    con.execute(f"CREATE SCHEMA IF NOT EXISTS {qident(ARCHIVE_DB)}.{qident(ARCHIVE_SCHEMA)}")
    cpm_snap = f"canonical_patient_master_histology_pre_mig178_{ts_tag}"
    events_snap = f"canonical_path_malignant_events_v1_pre_mig178_{ts_tag}"
    rollup_snap = f"canonical_path_malignant_patient_rollup_v1_pre_mig178_{ts_tag}"
    cpm_fq = f"{qident(ARCHIVE_DB)}.{qident(ARCHIVE_SCHEMA)}.{qident(cpm_snap)}"
    events_fq = f"{qident(ARCHIVE_DB)}.{qident(ARCHIVE_SCHEMA)}.{qident(events_snap)}"
    rollup_fq = f"{qident(ARCHIVE_DB)}.{qident(ARCHIVE_SCHEMA)}.{qident(rollup_snap)}"
    con.execute(
        f"""
        CREATE TABLE {cpm_fq} AS
        SELECT research_id, histologic_types_all, histologic_variants_all,
               path_histology_raw, path_histology_variant_raw, cpm_built_at
        FROM main.canonical_patient_master
        """
    )
    con.execute(f"CREATE TABLE {events_fq} AS SELECT * FROM main.canonical_path_malignant_events_v1")
    con.execute(f"CREATE TABLE {rollup_fq} AS SELECT * FROM main.canonical_path_malignant_patient_rollup_v1")
    return cpm_fq, events_fq, rollup_fq


