# Figure 4 — Forest plot of management-impact Δ (with bootstrap 95% CI)

def figure_4():
    rows = []
    with open(TABLES / "table_4_management_impact_bootstrap.csv") as f:
        rows = list(csv.DictReader(f))
    # Sort transitions by absolute Δ
    rows.sort(key=lambda r: abs(float(r["delta_pp"])), reverse=True)

    fig, ax = plt.subplots(figsize=(11, 6))
    labels = [r["transition"] for r in rows]
    deltas = [float(r["delta_pp"]) for r in rows]
    los    = [float(r["ci_lo_pp"]) for r in rows]
    his    = [float(r["ci_hi_pp"]) for r in rows]
    ys = list(range(len(labels)))[::-1]

    ax.axvline(0, color="gray", lw=0.8, ls="--")
    for y, d, lo, hi in zip(ys, deltas, los, his):
        color = "#d62728" if d < 0 else "#2ca02c"
        ax.errorbar(d, y, xerr=[[d - lo], [hi - d]], fmt="o",
                    color=color, capsize=4, lw=1.6, markersize=7)
    ax.set_yticks(ys)
    ax.set_yticklabels(labels, fontsize=9)
    ax.set_xlabel("Δ definitive total thyroidectomy at index (percentage points)\nNegative = reclassification de-escalates surgical management; positive = escalates")
    ax.set_title("M088 Figure 4 — Management impact of 2022 WHO reclassification\nForest plot of Δ definitive-total-thyroidectomy rate (target − historical), bootstrap 95% CI (1000 iter)")
    ax.grid(axis="x", lw=0.4, alpha=0.4)
    out = FIGURES / "figure_4_forest.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"Wrote {out}")

