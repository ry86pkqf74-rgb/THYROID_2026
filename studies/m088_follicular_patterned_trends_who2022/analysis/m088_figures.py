# Figure 3 — Sankey-style historical → 2022 WHO

def figure_3():
    """
    A custom matplotlib Sankey-like figure.
    Left side: historical labels (pre-2022 WHO 4th).
    Right side: 2022 WHO labels (with oncocytic family separated).
    Flow widths proportional to n.
    """
    # Historical → 2022 WHO mapping with patient counts
    flows = [
        ("Follicular adenoma (n=707)",                 "Follicular adenoma",               705, "#1f77b4"),
        ("Follicular adenoma (n=707)",                 "FT-UMP (Tier A)",                  2,   "#1f77b4"),  # approx, strict bound
        ("Hurthle cell adenoma (n=143)",               "Oncocytic adenoma",                143, "#ff7f0e"),
        ("FT-UMP, historical (n=34)",                  "FT-UMP",                           34,  "#9467bd"),  # most stay
        ("Atypical FA (n=33)",                         "FT-UMP (from atypical FA)",        33,  "#bcbd22"),
        ("NIFTP (n=116)",                              "NIFTP",                            116, "#17becf"),
        ("FTC, NOS (n=106)",                           "FTC, NOS",                         106, "#2ca02c"),
        ("FTC, minimally invasive (n=169)",            "FTC, minimally invasive (Tier A strict)", 167, "#d62728"),
        ("FTC, minimally invasive (n=169)",            "FT-UMP (Tier A strict)",           2,   "#d62728"),
        ("FTC, oncocytic variant (n=209)",             "Oncocytic carcinoma",              209, "#9467bd"),
        ("FTC, widely invasive (n=12)",                "FTC, widely invasive",             12,  "#ff7f0e"),
        ("Hurthle cell carcinoma (n=2)",               "Oncocytic carcinoma",              2,   "#8c564b"),
        ("DHGTC (n=11)",                               "DHGTC",                            11,  "#e377c2"),
        ("PDTC (n=1)",                                 "PDTC",                             1,   "#7f7f7f"),
        ("Hyalinizing trabecular tumor (n=4)",         "Hyalinizing trabecular tumor",     4,   "#7f7f7f"),
    ]

    # Build node lists preserving order
    seen_l, seen_r = [], []
    for s, t, _, _ in flows:
        if s not in seen_l: seen_l.append(s)
        if t not in seen_r: seen_r.append(t)

    # Assign vertical positions proportional to n
    def y_positions(nodes, side):
        totals = {}
        for s, t, n, _ in flows:
            k = s if side == "left" else t
            totals[k] = totals.get(k, 0) + n
        ord_nodes = [n for n in nodes]
        pos = {}
        running = 0
        gap = 8
        max_total = sum(totals.values()) if side == "left" else sum(totals.values())
        # Sort by total descending for visual clarity
        ord_nodes.sort(key=lambda nm: -totals[nm])
        for nm in ord_nodes:
            h = totals[nm]
            pos[nm] = (running, running + h)
            running += h + gap
        return pos, running

    Lpos, Lspan = y_positions(seen_l, "left")
    Rpos, Rspan = y_positions(seen_r, "right")

    fig, ax = plt.subplots(figsize=(13, 11))
    ax.set_xlim(0, 100)
    ax.set_ylim(0, max(Lspan, Rspan) + 5)
    ax.invert_yaxis()
    ax.axis("off")

    # Draw nodes
    for nm, (lo, hi) in Lpos.items():
        ax.add_patch(Rectangle((5, lo), 2.5, hi - lo, fc="#444", ec="black", lw=0.5))
        ax.text(4.5, (lo + hi) / 2, nm, ha="right", va="center", fontsize=8.5)
    for nm, (lo, hi) in Rpos.items():
        ax.add_patch(Rectangle((92.5, lo), 2.5, hi - lo, fc="#444", ec="black", lw=0.5))
        ax.text(95.5, (lo + hi) / 2, nm, ha="left", va="center", fontsize=8.5)

    # Track running offsets within each node so flow ribbons don't overlap
    Loff = {nm: lo for nm, (lo, _) in Lpos.items()}
    Roff = {nm: lo for nm, (lo, _) in Rpos.items()}

    for s, t, n, color in flows:
        lo_l = Loff[s]; lo_r = Roff[t]
        hi_l = lo_l + n; hi_r = lo_r + n
        Loff[s] = hi_l; Roff[t] = hi_r
        # Bezier path
        x_l, x_r = 7.5, 92.5
        verts_top = [(x_l, lo_l), ((x_l + x_r) / 2, lo_l), ((x_l + x_r) / 2, lo_r), (x_r, lo_r)]
        verts_bot = [(x_r, hi_r), ((x_l + x_r) / 2, hi_r), ((x_l + x_r) / 2, hi_l), (x_l, hi_l)]
        codes_top = [MplPath.MOVETO, MplPath.CURVE4, MplPath.CURVE4, MplPath.CURVE4]
        codes_bot = [MplPath.LINETO, MplPath.CURVE4, MplPath.CURVE4, MplPath.CURVE4]
        verts = verts_top + verts_bot + [(x_l, lo_l)]
        codes = codes_top + codes_bot + [MplPath.CLOSEPOLY]
        path = MplPath(verts, codes)
        ax.add_patch(mpatches.PathPatch(path, fc=color, ec="none", alpha=0.55))

    ax.set_title("M088 Figure 3 — Sankey diagram: historical (pre-2022 WHO 4th) → 2022 WHO 5th label\nFlow width ∝ patient count. Tier A deterministic mapping.", fontsize=11)
    out = FIGURES / "figure_3_sankey.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"Wrote {out}")

