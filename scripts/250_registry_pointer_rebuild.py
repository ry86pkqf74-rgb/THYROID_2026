def update_normalized(con, extractions: dict[str, list[str]], do_writes: bool, log_file) -> int:
    n_updated = 0
    for table, cols in extractions.items():
        if not cols:
            continue
        if do_writes:
            csv = ";".join(cols)
            esc = csv.replace("'", "''")
            con.execute(
                f"""UPDATE manuscript_workspace.detail_table_registry_v1
                    SET feeds_master_columns_normalized = '{esc}'
                    WHERE detail_table_name = '{table.replace("'", "''")}'"""
            )
        n_updated += 1
    log(f"  rows {'updated' if do_writes else 'would update'}: {n_updated}", log_file)
    return n_updated


