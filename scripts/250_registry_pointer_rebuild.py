def snapshot_registry(con, run_ts: str) -> str:
    dest = f"detail_table_registry_v1_pre250_{run_ts}"
    full = f'{ARCHIVE_QUALIFIED}."{dest}"'
    con.execute(f"CREATE OR REPLACE TABLE {full} AS SELECT * FROM manuscript_workspace.detail_table_registry_v1")
    con.execute(
        f"""COMMENT ON TABLE {full} IS
            '{SCRIPT_TAG} ({RUN_DATE}) pre-rebuild snapshot of detail_table_registry_v1.
             Rollback source for the v1_1 normalization pass.'"""
    )
    return dest


def snapshot_pointer_view(con, run_ts: str) -> str:
    """Snapshot the canonical_detail_pointer_v1 view DDL into archive."""
    defn = con.execute("""
SELECT view_definition FROM information_schema.views
WHERE table_catalog=? AND table_schema='manuscript_workspace'
  AND table_name='canonical_detail_pointer_v1'
""", [PUBLICATION_DB]).fetchone()
    dest = f"canonical_detail_pointer_v1_pre250_{run_ts}"
    full = f'{ARCHIVE_QUALIFIED}."{dest}"'
    con.execute(f"DROP TABLE IF EXISTS {full}")
    con.execute(
        f"""CREATE TABLE {full} (
              view_name VARCHAR,
              view_definition VARCHAR,
              snapshotted_at TIMESTAMP
           )"""
    )
    con.execute(
        f"INSERT INTO {full} VALUES (?, ?, ?)",
        ["canonical_detail_pointer_v1", defn[0] if defn else None, datetime.now(timezone.utc)],
    )
    con.execute(
        f"""COMMENT ON TABLE {full} IS
            '{SCRIPT_TAG} ({RUN_DATE}) pre-rebuild DDL snapshot of
             canonical_detail_pointer_v1. Rollback source.'"""
    )
    return dest


