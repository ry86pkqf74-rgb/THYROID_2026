# Phrases that indicate the feeds field is non-CPM-column (skip extraction)
SKIP_FEED_PHRASES = (
    "(catalog)", "(self)", "(reference)", "(provenance)", "(linkage)",
    "(audit)", "(no direct cpm column)", "subset view", "feeds ", "upstream",
    "crosslink", "crosswalk", "specimen->assay", "specimen-level",
    "level-specific", "episode-level", "lesion-level", "exam-level",
    "component-level", "review artifact", "v1_1 migration",
)

IDENT_RE = re.compile(r"^[a-z_][a-z0-9_]*$")
WILDCARD_RE = re.compile(r"^([a-z_][a-z0-9_]*)\*$")


def parse_explicit_tokens(feeds: str) -> list[str]:
    """Tokenize feeds string by , ; newline; return identifier tokens."""
    if not feeds:
        return []
    out: list[str] = []
    for tok in re.split(r"[;,\n]+", feeds):
        tok = tok.strip().rstrip(".;:")
        if not tok:
            continue
        # Lowercase normalize for identifier match
        if IDENT_RE.match(tok):
            out.append(tok)
        elif WILDCARD_RE.match(tok):
            out.append(tok)  # keep wildcard form for prefix expansion
    return out


def extract_normalized(con, registry_row: dict, cpm_cols: set[str]) -> tuple[list[str], dict]:
    """Return (sorted-unique cpm column list, parse_metadata)."""
    name = registry_row["detail_table_name"]
    feeds = registry_row.get("feeds_master_columns") or ""
    feeds_low = feeds.lower()
    parse_meta: dict = {
        "explicit_tokens": [],
        "explicit_matched": [],
        "explicit_unmatched": [],
        "prefix_expanded": [],
        "wildcard_expanded": [],
        "skipped_reason": None,
    }

    # Skip fields that are pure non-CPM markers
    if any(phrase in feeds_low for phrase in SKIP_FEED_PHRASES if phrase != "upstream"):
        # Allow prefix expansion to still apply if domain map says so
        parse_meta["skipped_reason"] = "non-CPM marker phrase"
    if "upstream" in feeds_low or "subset view" in feeds_low:
        parse_meta["skipped_reason"] = (parse_meta["skipped_reason"] or "") + ";upstream/subset"

    matched: set[str] = set()

    # 1. Explicit token match
    tokens = parse_explicit_tokens(feeds)
    for tok in tokens:
        parse_meta["explicit_tokens"].append(tok)
        if WILDCARD_RE.match(tok):
            prefix = tok.rstrip("*")
            wexp = sorted(c for c in cpm_cols if c.startswith(prefix))
            parse_meta["wildcard_expanded"].extend(wexp)
            matched.update(wexp)
            parse_meta["explicit_matched"].append(tok)
        elif tok in cpm_cols:
            matched.add(tok)
            parse_meta["explicit_matched"].append(tok)
        else:
            parse_meta["explicit_unmatched"].append(tok)

    # 2. Domain-prefix expansion (registry-table -> CPM prefix)
    prefixes = DOMAIN_PREFIX_MAP.get(name, [])
    for pfx in prefixes:
        if pfx.endswith("_"):
            # Treat as prefix
            exp = sorted(c for c in cpm_cols if c.startswith(pfx))
        else:
            # Treat as exact column name
            exp = [pfx] if pfx in cpm_cols else []
        parse_meta["prefix_expanded"].extend(exp)
        matched.update(exp)

    return sorted(matched), parse_meta


def detect_collisions(extractions: dict[str, list[str]]) -> dict[str, list[str]]:
    """Return CPM_col -> list of registry tables claiming it (only collisions)."""
    claimers: dict[str, list[str]] = {}
    for table, cols in extractions.items():
        for c in cols:
            claimers.setdefault(c, []).append(table)
    return {c: sorted(set(ts)) for c, ts in claimers.items() if len(set(ts)) > 1}


