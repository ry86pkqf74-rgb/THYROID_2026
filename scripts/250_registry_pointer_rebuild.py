def write_review_table(con, parse_results: dict, collisions: dict, do_writes: bool, log_file) -> int:
    if not do_writes:
        log(f"  WOULD write review table (rows={len(parse_results)})", log_file)
        return len(parse_results)
    con.execute("CREATE SCHEMA IF NOT EXISTS manuscript_workspace")
    con.execute("DROP TABLE IF EXISTS manuscript_workspace.registry_normalization_review_v1_1")
    con.execute(
        """CREATE TABLE manuscript_workspace.registry_normalization_review_v1_1 (
             detail_table_name        VARCHAR,
             feeds_original           VARCHAR,
             feeds_normalized         VARCHAR,
             n_explicit_tokens        INTEGER,
             n_explicit_matched       INTEGER,
             n_explicit_unmatched     INTEGER,
             n_prefix_expanded        INTEGER,
             n_wildcard_expanded      INTEGER,
             explicit_unmatched_list  VARCHAR,
             skipped_reason           VARCHAR,
             collision_columns        VARCHAR,
             reviewed_at              TIMESTAMP
           )"""
    )
    rows = []
    for table, meta in parse_results.items():
        norm = meta["normalized_csv"]
        cols_in_collision = sorted(c for c, ts in collisions.items() if table in ts)
        rows.append((
            table,
            meta["feeds_original"],
            norm,
            len(meta["explicit_tokens"]),
            len(meta["explicit_matched"]),
            len(meta["explicit_unmatched"]),
            len(meta["prefix_expanded"]),
            len(meta["wildcard_expanded"]),
            ";".join(meta["explicit_unmatched"]),
            meta["skipped_reason"],
            ";".join(cols_in_collision),
            datetime.now(timezone.utc),
        ))
    con.executemany(
        "INSERT INTO manuscript_workspace.registry_normalization_review_v1_1 VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
        rows,
    )
    con.execute(
        f"""COMMENT ON TABLE manuscript_workspace.registry_normalization_review_v1_1 IS
            '{SCRIPT_TAG} ({RUN_DATE}). Per-registry-row parse + extraction audit
             for canonical_detail_pointer_v1 normalization. Surfaces unmatched
             tokens, prefix-expansion outcomes, and CPM column collisions
             across multiple registry rows.'"""
    )
    log(f"  wrote review table rows: {len(rows)}", log_file)
    return len(rows)


