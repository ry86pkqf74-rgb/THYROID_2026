def compute_mapping_stats(con, cpm_cols: list[str], extractions: dict[str, list[str]]) -> dict:
    # Reverse map: CPM col -> set of detail tables
    rev: dict[str, set[str]] = {c: set() for c in cpm_cols}
    for table, cols in extractions.items():
        for c in cols:
            if c in rev:
                rev[c].add(table)
    n_total = len(cpm_cols)
    n_mapped = sum(1 for c, ts in rev.items() if ts)
    n_unmapped = n_total - n_mapped
    n_unmapped_in_allowlist = sum(
        1 for c in cpm_cols if not rev[c] and is_natively_derived(c)
    )
    n_unmapped_real = n_unmapped - n_unmapped_in_allowlist
    # Top 20 cols with most detail-table mappings
    top_multi = sorted(rev.items(), key=lambda kv: -len(kv[1]))[:20]
    return {
        "n_total_cpm_cols": n_total,
        "n_mapped": n_mapped,
        "n_unmapped": n_unmapped,
        "n_unmapped_allowlist": n_unmapped_in_allowlist,
        "n_unmapped_real": n_unmapped_real,
        "mapped_pct": round(100.0 * n_mapped / n_total, 2),
        "top_multi_mapped": [
            {"col": c, "n_tables": len(ts), "tables": sorted(ts)} for c, ts in top_multi
        ],
        "unmapped_real_sample": sorted(
            [c for c in cpm_cols if not rev[c] and not is_natively_derived(c)]
        )[:30],
    }


