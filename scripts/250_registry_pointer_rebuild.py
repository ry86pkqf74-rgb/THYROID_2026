def preflight(con) -> dict:
    n_rows = con.execute(f"SELECT COUNT(*) FROM {CPM}").fetchone()[0]
    n_cols = con.execute(
        f"""SELECT COUNT(*) FROM information_schema.columns
            WHERE table_catalog='{PUBLICATION_DB}' AND table_schema='main'
              AND table_name='{CPM}'"""
    ).fetchone()[0]
    n_base = con.execute(
        f"""SELECT COUNT(*) FROM information_schema.tables
            WHERE table_catalog='{PUBLICATION_DB}' AND table_schema='main'
              AND table_type='BASE TABLE'"""
    ).fetchone()[0]
    n_reg = con.execute(
        "SELECT COUNT(*) FROM manuscript_workspace.detail_table_registry_v1"
    ).fetchone()[0]
    if n_rows != 10871:
        raise RuntimeError(f"CPM rows {n_rows} != 10871")
    return {
        "cpm_rows": n_rows,
        "cpm_cols": n_cols,
        "main_base_tables": n_base,
        "registry_rows": n_reg,
    }


