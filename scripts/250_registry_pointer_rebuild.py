# Phase 3C — add 7 missing registry rows
# ---------------------------------------------------------------------------

def add_missing_registry_rows(con, do_writes: bool, log_file) -> dict:
    existing = {
        r[0] for r in con.execute(
            "SELECT detail_table_name FROM manuscript_workspace.detail_table_registry_v1"
        ).fetchall()
    }
    to_add: list[dict] = []
    for row in MISSING_REGISTRY_ROWS:
        if row["detail_table_name"] in existing:
            log(f"  SKIP (already in registry): {row['detail_table_name']}", log_file)
            continue
        to_add.append(row)

    # Compute total_rows + total_patients for each new row from the live table
    for row in to_add:
        try:
            n = con.execute(f'SELECT COUNT(*) FROM main."{row["detail_table_name"]}"').fetchone()[0]
        except Exception:
            n = 0
        row["total_rows"] = n
        try:
            n_pt = con.execute(
                f'SELECT COUNT(DISTINCT research_id) FROM main."{row["detail_table_name"]}"'
            ).fetchone()[0]
        except Exception:
            n_pt = None
        row["total_patients"] = n_pt
        log(f"  ADD: {row['detail_table_name']:35s} rows={n} pts={n_pt} domain={row['domain']}", log_file)

    if do_writes and to_add:
        for row in to_add:
            con.execute(
                """INSERT INTO manuscript_workspace.detail_table_registry_v1
                   (detail_table_name, schema_name, join_key, grain,
                    total_rows, total_patients, domain,
                    feeds_master_columns, description, canonical_version)
                   VALUES (?,?,?,?,?,?,?,?,?,?)""",
                [
                    row["detail_table_name"], row["schema_name"], row["join_key"],
                    row["grain"], row["total_rows"], row["total_patients"],
                    row["domain"], row["feeds_master_columns"],
                    row["description"], row["canonical_version"],
                ],
            )
    return {"added": [r["detail_table_name"] for r in to_add], "n_added": len(to_add)}


