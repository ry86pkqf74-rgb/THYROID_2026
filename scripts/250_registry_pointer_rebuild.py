POINTER_VIEW_DDL_TEMPLATE = f"""\
CREATE VIEW manuscript_workspace.canonical_detail_pointer_v1 AS
WITH cpm AS (
  SELECT column_name AS master_column,
         data_type   AS master_column_type,
         ordinal_position
  FROM information_schema.columns
  WHERE table_catalog='{PUBLICATION_DB}'
    AND table_schema='main'
    AND table_name='canonical_patient_master'
),
reg AS (
  SELECT detail_table_name, schema_name, "domain",
         feeds_master_columns_normalized,
         total_rows, total_patients
  FROM thyroid_canonical_publication_v1_0.manuscript_workspace.detail_table_registry_v1
  WHERE feeds_master_columns_normalized IS NOT NULL
    AND feeds_master_columns_normalized <> ''
),
reg_exp AS (
  SELECT detail_table_name, schema_name, "domain",
         total_rows, total_patients,
         trim(fm) AS feeds_column
  FROM reg, unnest(string_split(feeds_master_columns_normalized, ';')) AS t(fm)
)
SELECT c.master_column,
       c.master_column_type,
       c.ordinal_position,
       e.detail_table_name,
       e.schema_name,
       e."domain",
       e.total_rows,
       e.total_patients
FROM cpm AS c
LEFT JOIN reg_exp AS e
  ON lower(trim(c.master_column)) = lower(trim(e.feeds_column))
ORDER BY c.ordinal_position, e.detail_table_name
"""


def rebuild_pointer_view(con, do_writes: bool, log_file) -> bool:
    if not do_writes:
        log("  WOULD DROP + CREATE canonical_detail_pointer_v1", log_file)
        return False
    con.execute("DROP VIEW IF EXISTS manuscript_workspace.canonical_detail_pointer_v1")
    con.execute(POINTER_VIEW_DDL_TEMPLATE)
    log("  rebuilt manuscript_workspace.canonical_detail_pointer_v1", log_file)
    return True


