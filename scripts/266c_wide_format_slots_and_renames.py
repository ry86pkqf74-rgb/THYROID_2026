def _cleanup_audit_keep_review(con) -> set[str]:
    """Return the set of table_names tagged KEEP_REVIEW in
    canonical_cleanup_audit_v1 (the big-cleanup audit table). Returns
    empty set if the table doesn't exist."""
    try:
        rows = con.execute(f"""
            SELECT DISTINCT table_name FROM {CLEANUP_AUDIT}
             WHERE UPPER(action) = 'KEEP_REVIEW'
                OR UPPER(disposition) = 'KEEP_REVIEW'
        """).fetchall()
        return {r[0] for r in rows}
    except Exception:
        return set()


def _views_referencing(con, *table_names: str) -> list[tuple[str, str]]:
    """Return list of (view_name, snippet) for views whose definition
    contains any of the supplied substrings (case-insensitive)."""
    if not table_names:
        return []
    likes = " OR ".join(
        f"LOWER(view_definition) LIKE '%{t.lower()}%'" for t in table_names
    )
    rows = con.execute(f"""
        SELECT table_name, SUBSTR(view_definition, 1, 240) AS snippet
          FROM information_schema.views
         WHERE table_catalog='{PUBLICATION_DB}'
           AND table_schema IN ('main', 'manuscript_workspace')
           AND ({likes})
         ORDER BY table_name
    """).fetchall()
    return [(r[0], r[1] or "") for r in rows]


def _column_present(con, table_fq: str, column: str) -> bool:
    schema, table = table_fq.split(".")[-2], table_fq.split(".")[-1]
    n = con.execute(f"""
        SELECT COUNT(*) FROM information_schema.columns
         WHERE table_catalog='{PUBLICATION_DB}'
           AND table_schema='{schema}'
           AND table_name='{table}'
           AND column_name=?
    """, [column]).fetchone()[0]
    return n > 0


