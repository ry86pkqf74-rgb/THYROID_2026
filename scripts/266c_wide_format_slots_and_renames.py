# Phase 2 (W1) — path_synoptics wide-format slot buildout
# ---------------------------------------------------------------------------
def phase_2(con, log, do_writes: bool) -> dict:
    log("\n## Phase 2 (W1) — path_synoptics ADD COLUMN + populate (40 cols)")

    # ADD COLUMN
    existing = {r[0] for r in con.execute(f"""
        SELECT column_name FROM information_schema.columns
         WHERE table_catalog='{PUBLICATION_DB}' AND table_schema='main'
           AND table_name='path_synoptics'
    """).fetchall()}
    added = []
    for col, typ in PSYN_NEW_COLUMNS:
        if col in existing:
            log(f"  SKIP (already present): {col}")
            continue
        sql = f'ALTER TABLE {PSYN} ADD COLUMN "{col}" {typ}'
        _exec(con, sql, log, do_writes, label=f"add:{col}")
        added.append(col)

    # Profile path_synoptics grain. Per live verification 2026-04-17:
    # 11,688 rows / 10,871 patients / 11,687 distinct (research_id, surg_date)
    # — i.e. one row per surgery per patient. 761 patients have multiple
    # surgeries (completion thyroidectomy, re-excision, etc.). The W1 wide
    # pivot MUST therefore join CTC -> path_synoptics on (research_id,
    # surg_date), NOT on research_id alone, otherwise per-surgery staging
    # gets corrupted into a per-patient broadcast across all surgeries.
    # Phase 0 already confirmed both tables carry the join columns.
    grain = con.execute(f"""
        SELECT
          COUNT(*)                                                AS n_rows,
          COUNT(DISTINCT research_id)                             AS n_pts,
          COUNT(DISTINCT (CAST(research_id AS VARCHAR) || '|' ||
                          CAST(surg_date AS VARCHAR)))            AS n_pt_surg
        FROM {PSYN}
    """).fetchone()
    log(f"  path_synoptics grain: {grain[0]} rows / {grain[1]} pts / "
        f"{grain[2]} (research_id, surg_date) keys")
    if grain[0] != grain[2]:
        log(f"  NOTE: {grain[0] - grain[2]} duplicate (research_id, surg_date) "
            f"row(s) in path_synoptics. The wide pivot will give those rows "
            f"identical AJCC slot values (per-surgery deterministic UPDATE), "
            f"so the per-(rid, surg_date) distinctness assertion below "
            f"remains valid.")
    log("  NOTE: 2,449 benign tumor-free CPM patients are intentionally "
        "absent from canonical_tumor_characteristics_v1 (cohort_scoping "
        "convention). Their path_synoptics rows receive NULL in every "
        "new tumor_N_*_ajcc{7,8} column by design — this is correct, "
        "not a population gap.")

    # Tumor_ordinal > 5 overflow
    overflow = con.execute(f"""
        SELECT
          CAST(research_id AS VARCHAR) AS research_id,
          surgery_episode_id           AS surgery_episode_id,
          tumor_ordinal                AS tumor_ordinal,
          primary_histology            AS primary_histology,
          t_stage_ajcc8                AS t_stage_ajcc8,
          stage_group_ajcc8            AS stage_group_ajcc8
        FROM {CTC}
       WHERE tumor_ordinal > 5
       ORDER BY research_id, surgery_episode_id, tumor_ordinal
    """).fetchall()
    with OVERFLOW_CSV.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["research_id", "surgery_episode_id", "tumor_ordinal",
                    "primary_histology", "t_stage_ajcc8", "stage_group_ajcc8"])
        w.writerows(overflow)
    log(f"  tumor_ordinal>5 overflow rows: {len(overflow)} -> {OVERFLOW_CSV.name}")

    # Build wide per-(research_id, surg_date) pivot from CTC (ordinal 1..5).
    # Per-surgery grain (NOT per-patient) — see grain notes above.
    case_clauses: list[str] = []
    for n in range(1, 6):
        for ed in (7, 8):
            for f in PSYN_FIELDS:
                src_col = f if f != "stage_group" else f"stage_group_ajcc{ed}"
                src_col = src_col if f == "stage_group" else f"{f}_ajcc{ed}"
                tgt_col = (f"tumor_{n}_t_stage_ajcc{ed}" if f == "t_stage" else
                           f"tumor_{n}_n_stage_ajcc{ed}" if f == "n_stage" else
                           f"tumor_{n}_m_stage_ajcc{ed}" if f == "m_stage" else
                           f"tumor_{n}_stage_group_ajcc{ed}")
                case_clauses.append(
                    f"MAX(CASE WHEN ctc.tumor_ordinal = {n} THEN ctc.{src_col} END) "
                    f'AS "{tgt_col}"'
                )
    select_block = ",\n          ".join(case_clauses)

    update_set = ", ".join(
        f'"{c}" = w."{c}"' for c, _ in PSYN_NEW_COLUMNS
    )
    sql_update = f"""
        WITH wide AS (
          SELECT
            CAST(ctc.research_id AS VARCHAR)                    AS research_id,
            ctc.surgery_date                                     AS surg_date,
            {select_block}
          FROM {CTC} AS ctc
          WHERE ctc.tumor_ordinal BETWEEN 1 AND 5
          GROUP BY 1, 2
        )
        UPDATE {PSYN} AS p
           SET {update_set}
          FROM wide AS w
         WHERE CAST(p.research_id AS VARCHAR) = w.research_id
           AND p.surg_date = w.surg_date
    """
    _exec(con, sql_update, log, do_writes, label="psyn_wide_update")

    # Per-surgery determinism assertion (per user spec). Confirms the UPDATE
    # produced at most one distinct tumor_1_t_stage_ajcc7 per (research_id,
    # surg_date) — i.e. join was per-surgery, not per-patient broadcast.
    if do_writes:
        n_violations = int(con.execute(f"""
            SELECT COUNT(*) FROM (
              SELECT research_id, surg_date,
                     COUNT(DISTINCT tumor_1_t_stage_ajcc7) AS n_distinct
                FROM {PSYN}
               GROUP BY research_id, surg_date
              HAVING COUNT(DISTINCT tumor_1_t_stage_ajcc7) > 1
            ) AS v
        """).fetchone()[0])
        log(f"  per-surgery determinism check: "
            f"{n_violations} (research_id, surg_date) group(s) with > 1 "
            f"distinct tumor_1_t_stage_ajcc7 — must be 0")
        if n_violations > 0:
            raise SystemExit(
                f"W1 per-surgery determinism violated: {n_violations} "
                f"(research_id, surg_date) groups have > 1 distinct "
                f"tumor_1_t_stage_ajcc7. Wide pivot regressed to broadcast."
            )

    # Profile + COMMENT-deprecate legacy fragment columns
    log("  profiling legacy fragment columns ...")
    fragment_rows = []
    for col in PSYN_LEGACY_FRAGMENT_COLS:
        try:
            n_total, n_nn = con.execute(f"""
                SELECT COUNT(*),
                       COUNT(*) FILTER (WHERE "{col}" IS NOT NULL)
                  FROM {PSYN}
            """).fetchone()
            pct = round(100.0 * n_nn / n_total, 3) if n_total else 0.0
            fragment_rows.append((col, n_total, n_nn, pct, "present"))
            log(f"    {col}: {n_nn}/{n_total} ({pct}%)")
            comment = (
                f"Deprecated 2026-04-17 by Script 266c. Legacy fragment "
                f"column. Per-tumor staging now lives in tumor_N_t_stage_"
                f"ajcc7 / tumor_N_t_stage_ajcc8 (and n/m/stage_group "
                f"counterparts) populated from canonical_tumor_"
                f"characteristics_v1. Population at 266c run time: {n_nn}"
                f" of {n_total} ({pct}%). NOT renamed (raw_source rule)."
            )
            sql_c = f'COMMENT ON COLUMN {PSYN}."{col}" IS {_quote(comment)}'
            _exec(con, sql_c, log, do_writes, label=f"comment_legacy:{col}")
        except Exception as e:
            fragment_rows.append((col, None, None, None, f"absent: {e!s}"))
            log(f"    {col}: absent ({e})")
    with FRAGMENT_PROFILE_CSV.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["column", "n_total_rows", "n_non_null", "pct_non_null", "status"])
        w.writerows(fragment_rows)
    log(f"  legacy fragment profile -> {FRAGMENT_PROFILE_CSV.name}")

    # COMMENT ON COLUMN for each new wide col
    for col, _ in PSYN_NEW_COLUMNS:
        m = re.match(r"tumor_(\d+)_(t|n|m|stage)_(stage|group)_ajcc(7|8)", col)
        if not m:
            continue
        n_idx, _, _, ed = m.groups()
        msg = (
            f"Per-tumor AJCC{ed} value for tumor slot {n_idx}, populated by "
            f"Script 266c (2026-04-17) via wide pivot from "
            f"canonical_tumor_characteristics_v1.{'t_stage' if 't_stage' in col else 'n_stage' if 'n_stage' in col else 'm_stage' if 'm_stage' in col else 'stage_group'}_ajcc{ed}. "
            f"Tumor slots > 5 logged to scripts/output/{OVERFLOW_CSV.name}."
        )
        sql_c = f'COMMENT ON COLUMN {PSYN}."{col}" IS {_quote(msg)}'
        _exec(con, sql_c, log, do_writes, label=f"comment:{col}")

    return {
        "added_columns": added,
        "skipped_present": [c for c, _ in PSYN_NEW_COLUMNS if c in existing],
        "psyn_n_rows": int(grain[0]) if grain[0] is not None else None,
        "psyn_n_patients": int(grain[1]) if grain[1] is not None else None,
        "psyn_n_pt_surg_keys": int(grain[2]) if grain[2] is not None else None,
        "tumor_ordinal_gt5_count": len(overflow),
        "legacy_fragment_profile": fragment_rows,
    }


