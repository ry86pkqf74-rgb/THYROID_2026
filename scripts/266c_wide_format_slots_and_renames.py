DEPRECATED_NAME_RE = re.compile(r"_deprecated_", re.IGNORECASE)


def phase_5(con, log, do_writes: bool) -> dict:
    log("\n## Phase 5 (W4) — archive sweep")

    keep_review = _cleanup_audit_keep_review(con)
    keep_list = _keep_list_excludes(con)
    log(f"  big-cleanup KEEP_REVIEW set: {sorted(keep_review)[:8]}"
        f"{' ...' if len(keep_review) > 8 else ''} (total {len(keep_review)})")
    log(f"  main_schema_keep_list_v1 set: {sorted(keep_list)[:8]}"
        f"{' ...' if len(keep_list) > 8 else ''} (total {len(keep_list)})")

    # Build full candidate list:
    #   (a) explicit candidates from EXPLICIT_ARCHIVE_CANDIDATES (if still present)
    #   (b) any main-schema table whose name matches _deprecated_*
    queryable_main = _queryable_main_tables(con)
    log(f"  queryable main tables: {len(queryable_main)}")

    candidates: list[tuple[str, str, str]] = []  # (schema, table, reason)
    for schema, name in EXPLICIT_ARCHIVE_CANDIDATES:
        try:
            n = con.execute(
                f'SELECT COUNT(*) FROM {PUBLICATION_DB}."{schema}"."{name}"'
            ).fetchone()[0]
            candidates.append((schema, name,
                               f"explicit_supersession (n_rows={n})"))
        except Exception:
            log(f"  explicit candidate {schema}.{name} absent — skip.")

    for tbl in sorted(queryable_main):
        if DEPRECATED_NAME_RE.search(tbl):
            candidates.append(("main", tbl, "deprecated_name_pattern"))

    log(f"  total archive candidates: {len(candidates)}")
    for sch, t, why in candidates:
        log(f"    - {sch}.{t} :: {why}")

    manifest_rows = []
    skipped_rows = []
    archived_count = 0
    skipped_count = 0
    ts = utc_ts()

    for schema, name, reason in candidates:
        # Keep-list / KEEP_REVIEW exclusion
        if name in keep_review or name in keep_list:
            why = ("KEEP_REVIEW (canonical_cleanup_audit_v1)" if name in keep_review
                   else "main_schema_keep_list_v1 sunset_trigger not fired")
            log(f"  SKIP {schema}.{name} :: {why}")
            skipped_rows.append({
                "schema": schema, "name": name, "reason": reason,
                "skipped_because": why,
            })
            skipped_count += 1
            continue

        # View-dependency check per candidate
        refs = _views_referencing(con, name)
        if refs:
            log(f"  SKIP {schema}.{name} :: referenced by views: "
                f"{[v for v, _ in refs]}")
            skipped_rows.append({
                "schema": schema, "name": name, "reason": reason,
                "skipped_because": f"view_refs: {[v for v, _ in refs]}",
            })
            skipped_count += 1
            continue

        # Idempotency check: if a prior 266c run already archived this
        # candidate (matching <name>_pre266c_<UTC> in archive_pub_v1_0),
        # skip both the archive write and the DROP. The previous run is
        # the source of truth; do not double-archive.
        try:
            already = con.execute(f"""
                SELECT 1 FROM information_schema.tables
                 WHERE table_catalog='{ARCHIVE_DB}'
                   AND table_schema='archive_pub_v1_0'
                   AND table_name LIKE '{name}_pre266c_%'
                 LIMIT 1
            """).fetchone()
        except Exception:
            already = None
        if already is not None:
            log(f"  SKIP {schema}.{name} :: already_archived "
                f"(prior 266c run produced {name}_pre266c_*)")
            skipped_rows.append({
                "schema": schema, "name": name, "reason": reason,
                "skipped_because": (
                    f"already_archived: {ARCHIVE_DB}.archive_pub_v1_0."
                    f"{name}_pre266c_*"
                ),
            })
            skipped_count += 1
            continue

        # Pre-row count
        try:
            n_before = con.execute(
                f'SELECT COUNT(*) FROM {PUBLICATION_DB}."{schema}"."{name}"'
            ).fetchone()[0]
        except Exception as e:
            log(f"  SKIP {schema}.{name} :: not queryable ({e})")
            skipped_rows.append({
                "schema": schema, "name": name, "reason": reason,
                "skipped_because": f"not_queryable: {e!s}",
            })
            skipped_count += 1
            continue

        # CTAS to archive then DROP from main
        archive_name = f"{name}_pre266c_{ts}"
        archive_fq = f'{ARCHIVE_QUALIFIED}."{archive_name}"'
        src_fq = f'{PUBLICATION_DB}."{schema}"."{name}"'
        sql_archive = f"CREATE TABLE {archive_fq} AS SELECT * FROM {src_fq}"
        _exec(con, sql_archive, log, do_writes, label=f"archive:{name}")

        archive_comment = (
            f"Script 266c (2026-04-17) archive of {src_fq}. Reason: "
            f"{reason}. Source-side DROP follows in same transaction. "
            f"To restore: CREATE TABLE {src_fq} AS SELECT * FROM {archive_fq}."
        )
        _exec(con,
              f"COMMENT ON TABLE {archive_fq} IS {_quote(archive_comment)}",
              log, do_writes, label=f"comment_archive:{name}")

        sql_drop = f"DROP TABLE {src_fq}"
        _exec(con, sql_drop, log, do_writes, label=f"drop:{name}")

        # Per catalog_vs_queryable_drift: probe to confirm DROP took effect
        if do_writes:
            still_queryable = True
            try:
                con.execute(f"SELECT 1 FROM {src_fq} LIMIT 1").fetchone()
            except Exception:
                still_queryable = False
            log(f"    post-DROP queryable check: still_queryable={still_queryable}")
            if still_queryable:
                raise SystemExit(
                    f"DROP {src_fq} did not remove the table. HALT."
                )

        manifest_rows.append({
            "schema": schema, "name": name, "reason": reason,
            "n_rows_before": n_before, "archive_dest": archive_fq,
            "action": "archived_and_dropped",
        })
        archived_count += 1

    # Write manifest
    with ARCHIVE_MANIFEST_CSV.open("w", newline="") as f:
        cols = ["schema", "name", "reason", "n_rows_before",
                "archive_dest", "action", "skipped_because"]
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in manifest_rows:
            w.writerow(r)
        for r in skipped_rows:
            w.writerow({**r, "action": "skipped"})
    log(f"  archive manifest -> {ARCHIVE_MANIFEST_CSV.name}: "
        f"{archived_count} archived, {skipped_count} skipped")

    return {
        "archived_count": archived_count,
        "skipped_count": skipped_count,
        "manifest": manifest_rows,
        "skipped": skipped_rows,
    }


