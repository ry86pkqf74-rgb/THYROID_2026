# Phase 4 (W3) — un-versioned column rename pass (DESTRUCTIVE)
# ---------------------------------------------------------------------------
def phase_4(con, log, do_writes: bool) -> dict:
    log("\n## Phase 4 (W3) — un-versioned column RENAMES (destructive)")

    # Re-run the view-dependency PRE-GATE inside this phase as well, so
    # a view added between Phase 0 and Phase 4 still halts us.
    refs = _views_referencing(con,
                              "canonical_tumor_characteristics_v1",
                              "tumor_episode_master_v2")
    log(f"  RE-CHECK view dep   : {len(refs)} ref(s)")
    if refs:
        raise SystemExit(
            f"View dependency PRE-GATE failed at Phase 4 entry: "
            f"{[v for v, _ in refs]} now references CTC or TEM. HALT."
        )

    renames_applied = []
    for tbl, pairs in RENAME_TARGETS:
        for old, new in pairs:
            # Idempotency: if old is already gone and new is present, skip.
            old_present = _column_present(con, tbl, old)
            new_present = _column_present(con, tbl, new)
            if not old_present and new_present:
                log(f"  SKIP (already renamed): {tbl}.{old} -> {new}")
                continue
            if not old_present and not new_present:
                log(f"  SKIP (column absent — likely never existed): {tbl}.{old}")
                continue
            if old_present and new_present:
                raise SystemExit(
                    f"Refusing to rename: BOTH {tbl}.{old} and {tbl}.{new} "
                    f"present. Manual reconciliation required."
                )
            sql = f'ALTER TABLE {tbl} RENAME COLUMN "{old}" TO "{new}"'
            _exec(con, sql, log, do_writes, label=f"rename:{tbl}:{old}")
            renames_applied.append({"table": tbl, "old": old, "new": new})

            # COMMENT immediately after rename so the deprecation note
            # travels with the column.
            comment_sql = (
                f'COMMENT ON COLUMN {tbl}."{new}" IS '
                f"{_quote(RENAME_DEPRECATION_NOTE)}"
            )
            _exec(con, comment_sql, log, do_writes, label=f"comment:{tbl}:{new}")

    return {"renames_applied": renames_applied}


