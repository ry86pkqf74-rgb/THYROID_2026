    existing = {r[0] for r in con.execute(f"""
        SELECT column_name FROM information_schema.columns
         WHERE table_catalog='{PUBLICATION_DB}' AND table_schema='main'
           AND table_name='tumor_pathology'
    """).fetchall()}

    # Sanity: confirm AJCC8 histology_1 quartet pre-exists (do NOT overwrite).
    a8_existing = [c for c in (
        "histology_1_t_stage_ajcc8", "histology_1_n_stage_ajcc8",
        "histology_1_m_stage_ajcc8", "histology_1_overall_stage_ajcc8",
    ) if c in existing]
    log(f"  pre-existing histology_1 AJCC8 quartet : {a8_existing}")
    if len(a8_existing) != 4:
        log(f"  WARNING: expected all 4 of histology_1_*_stage_ajcc8 to "
            f"pre-exist; got {a8_existing}. 266c will NOT auto-add them — "
            f"that is 266b/big-cleanup territory.")

    # Sanity: confirm tumor_pathology has surgery_date column (VARCHAR per
    # live schema). The W2 join requires it.
    if "surgery_date" not in existing:
        raise SystemExit(
            "tumor_pathology lacks surgery_date column — cannot perform "
            "W2 join. Live schema verification required."
        )

    # ADD the 4 new AJCC7 columns
    added = []
    for col, typ in TPATH_NEW_COLUMNS:
        if col in existing:
            log(f"  SKIP (already present): {col}")
            continue
        sql = f'ALTER TABLE {TPATH} ADD COLUMN "{col}" {typ}'
        _exec(con, sql, log, do_writes, label=f"add:{col}")
        added.append(col)

    # Population: dominant-tumor pick per (research_id, surgery_date) from CTC,
    # joined to tumor_pathology via CAST(ctc.research_id AS VARCHAR) and
    # ctc.surgery_date = CAST(tp.surgery_date AS TIMESTAMP).
    # Dominance rule: largest tumor_size_cm_per_surgery, ties broken by lowest
    # tumor_ordinal. Deterministic — no slot-string matching required.
    sql_update = f"""
        WITH ranked AS (
          SELECT
            CAST(ctc.research_id AS VARCHAR)                  AS research_id,
            ctc.surgery_date                                   AS surgery_date,
            ctc.tumor_ordinal                                  AS tumor_ordinal,
            ctc.tumor_size_cm_per_surgery                      AS tumor_size_cm_per_surgery,
            ctc.t_stage_ajcc7                                  AS t_stage_ajcc7,
            ctc.n_stage_ajcc7                                  AS n_stage_ajcc7,
            ctc.m_stage_ajcc7                                  AS m_stage_ajcc7,
            ctc.overall_stage_ajcc7                            AS overall_stage_ajcc7,
            ROW_NUMBER() OVER (
              PARTITION BY CAST(ctc.research_id AS VARCHAR), ctc.surgery_date
              ORDER BY ctc.tumor_size_cm_per_surgery DESC NULLS LAST,
                       ctc.tumor_ordinal ASC NULLS LAST
            )                                                  AS dom_rank
          FROM {CTC} AS ctc
        ),
        dominant AS (
          SELECT
            research_id                                        AS research_id,
            surgery_date                                       AS surgery_date,
            t_stage_ajcc7                                      AS t_stage_ajcc7,
            n_stage_ajcc7                                      AS n_stage_ajcc7,
            m_stage_ajcc7                                      AS m_stage_ajcc7,
            overall_stage_ajcc7                                AS overall_stage_ajcc7
          FROM ranked
          WHERE dom_rank = 1
        )
        UPDATE {TPATH} AS tp
           SET histology_1_t_stage_ajcc7       = d.t_stage_ajcc7,
               histology_1_n_stage_ajcc7       = d.n_stage_ajcc7,
               histology_1_m_stage_ajcc7       = d.m_stage_ajcc7,
               histology_1_overall_stage_ajcc7 = d.overall_stage_ajcc7
          FROM dominant AS d
         WHERE CAST(tp.research_id AS VARCHAR) = d.research_id
           AND CAST(tp.surgery_date AS TIMESTAMP) = d.surgery_date
    """
    _exec(con, sql_update, log, do_writes, label="tpath_dominant_update")

    # COMMENT ON COLUMN for each of the 4 new cols
    for col, _ in TPATH_NEW_COLUMNS:
        comp_match = re.match(r"histology_1_(t|n|m|overall)_stage_ajcc7", col)
        if not comp_match:
            continue
        comp = comp_match.group(1)
        msg = (
            f"AJCC7 {comp.upper()}-stage for the histology_1 slot, populated "
            f"by Script 266c (2026-04-17) from the dominant tumor per "
            f"(research_id, surgery_date) in canonical_tumor_characteristics_v1 "
            f"(dominance: largest tumor_size_cm_per_surgery, ties by lowest "
            f"tumor_ordinal). Companion AJCC8 column histology_1_{comp}_stage"
            f"_ajcc8 already existed pre-266c — left untouched."
        )
        sql_c = f'COMMENT ON COLUMN {TPATH}."{col}" IS {_quote(msg)}'
        _exec(con, sql_c, log, do_writes, label=f"comment:{col}")

    return {
        "added_columns": added,
        "skipped_present": [c for c, _ in TPATH_NEW_COLUMNS if c in existing],
        "ajcc8_quartet_preexisting": a8_existing,
    }


