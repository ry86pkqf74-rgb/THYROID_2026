# Phase 6 (W5) — __readme rebuild + view smoke check
# ---------------------------------------------------------------------------
def phase_6(con, log, do_writes: bool) -> dict:
    log("\n## Phase 6 (W5) — __readme rebuild + view smoke check")

    queryable = sorted(_queryable_main_tables(con))
    log(f"  queryable main tables (post-archive): {len(queryable)}")

    if do_writes:
        _exec(con, f"DROP TABLE IF EXISTS {README_TBL}", log, do_writes,
              label="drop_readme")
        _exec(con, f"""
            CREATE TABLE {README_TBL} (
                table_name VARCHAR PRIMARY KEY,
                n_rows BIGINT,
                n_distinct_research_id BIGINT,
                description VARCHAR,
                inventoried_at TIMESTAMP
            )
        """, log, do_writes, label="create_readme")

        # Filter __readme out of the loop -- it gets inserted explicitly as
        # the self-row below. Without this filter the loop inserts __readme
        # once (because _queryable_main_tables() includes it), then the
        # explicit self-row insert raises a PRIMARY KEY duplicate-key
        # constraint error (2026-04-18 fix).
        queryable_no_self = [t for t in queryable if t != "__readme"]
        for tbl in queryable_no_self:
            try:
                n_rows = int(con.execute(
                    f'SELECT COUNT(*) FROM {PUBLICATION_DB}.main."{tbl}"'
                ).fetchone()[0])
            except Exception:
                continue
            try:
                n_pat = int(con.execute(
                    f'SELECT COUNT(DISTINCT research_id) FROM '
                    f'{PUBLICATION_DB}.main."{tbl}"'
                ).fetchone()[0])
            except Exception:
                n_pat = None
            con.execute(
                f"INSERT INTO {README_TBL} VALUES (?, ?, ?, ?, ?)",
                [tbl, n_rows, n_pat,
                 "Re-inventoried by Script 266c (2026-04-17) via "
                 "queryable enumeration (catalog_vs_queryable_drift convention).",
                 datetime.now(timezone.utc)],
            )
        # Self-row inclusion (per Script 265 pattern). Inserted once here
        # to avoid the duplicate-key bug on the loop self-insertion path.
        n_readme = int(con.execute(f"SELECT COUNT(*) FROM {README_TBL}").fetchone()[0])
        con.execute(
            f"INSERT INTO {README_TBL} VALUES (?, ?, ?, ?, ?)",
            ["__readme", n_readme + 1, None,
             "Self-row. Auto-rebuilt by Script 266c.",
             datetime.now(timezone.utc)],
        )
        comment = (
            "Script 266c (2026-04-17) queryable enumeration of main "
            "BASE TABLEs. Auto-rebuilt by Script 266c after the "
            "archive sweep + un-versioned column rename pass."
        ).replace("'", "''")
        con.execute(f"COMMENT ON TABLE {README_TBL} IS '{comment}'")
        log(f"  __readme rebuilt with {n_readme + 1} rows.")
    else:
        log(f"  PLAN: would rebuild __readme with ~{len(queryable) + 1} rows.")

    # View smoke check
    views = [r[0] for r in con.execute(f"""
        SELECT table_name FROM information_schema.views
         WHERE table_catalog='{PUBLICATION_DB}'
           AND table_schema='manuscript_workspace'
         ORDER BY table_name
    """).fetchall()]
    log(f"  smoke-checking {len(views)} views ...")
    rows = []
    n_ok = 0
    n_fail = 0
    for v in views:
        try:
            n = con.execute(
                f'SELECT COUNT(*) FROM {PUBLICATION_DB}.manuscript_workspace."{v}"'
            ).fetchone()[0]
            rows.append((v, "ok", n))
            n_ok += 1
        except Exception as e:
            msg = str(e).splitlines()[0][:300]
            rows.append((v, "error", msg))
            n_fail += 1
    with VIEW_SMOKE_CSV.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["view_name", "status", "row_count_or_error"])
        w.writerows(rows)
    log(f"  smoke result: ok={n_ok} error={n_fail}")
    if n_fail:
        broken = [r[0] for r in rows if r[1] == "error"][:10]
        raise SystemExit(f"View smoke check failed: {n_fail} broken: {broken}")

    return {"queryable_main_tables": len(queryable),
            "views_total": len(views), "views_ok": n_ok, "views_error": n_fail}


